#!/usr/bin/env bash
# Black-box fixture for install-operator-tools.sh. It builds a fake worker
# bundle and a real generated trust artifact inside one temporary root and
# proves digest verification, archive preflight, selective extraction,
# dry-run non-mutation, exact replay and fail-closed replacement. It never
# touches a real system path.
set -euo pipefail

usage() {
  cat >&2 <<'EOF'
usage: install-operator-tools-fixture.sh --openssl /absolute/openssl-with-ed25519
EOF
}

openssl_binary=
while [[ $# -gt 0 ]]; do
  case "$1" in
    --openssl)
      [[ $# -ge 2 ]] || { usage; exit 2; }
      openssl_binary=$2
      shift 2
      ;;
    *)
      usage
      exit 2
      ;;
  esac
done
[[ $openssl_binary == /* && -x $openssl_binary ]] || {
  echo "--openssl must name an absolute Ed25519-capable openssl" >&2
  exit 2
}

fixture_dir="$(cd "$(dirname "$0")" && pwd)"
installer="$fixture_dir/install-operator-tools.sh"
trust_tool="$fixture_dir/production-cutover-operator-trust.py"
[[ -f $installer && -f $trust_tool ]] || {
  echo "installer or trust tool is missing next to this fixture" >&2
  exit 2
}

fail() {
  echo "FIXTURE FAILURE: $*" >&2
  exit 1
}

expect_failure() {
  local label=$1
  shift
  if "$@" >/dev/null 2>&1; then
    fail "$label unexpectedly succeeded"
  fi
}

root=$(mktemp -d "${TMPDIR:-/tmp}/cats-operator-tools-fixture.XXXXXX")
cleanup() { rm -rf -- "$root"; }
trap cleanup EXIT
# macOS exposes its temporary root through a /var symlink; the authority tool
# deliberately rejects symlinked output ancestry, so resolve once here.
root=$(cd "$root" && pwd -P)
chmod 0700 "$root"

# --- fake worker bundle: operator tools plus members that must NOT install.
worker_root="$root/worker-root"
mkdir -m 0755 "$worker_root" "$worker_root/guest-runtime-release.v1"
printf '#!/bin/sh\necho fake cats CLI\n' > "$worker_root/cats"
printf '#!/bin/sh\necho fake schema verifier\n' \
  > "$worker_root/cats-usage-schema-v16-verifier"
printf '#!/bin/sh\necho fake terminal verifier\n' \
  > "$worker_root/cats-usage-terminal-receipt-verifier"
printf '#!/bin/sh\necho worker daemon must never install\n' \
  > "$worker_root/cats-noded"
printf 'fake guest payload\n' \
  > "$worker_root/guest-runtime-release.v1/manifest.v1.json"
chmod 0755 "$worker_root/cats" "$worker_root/cats-usage-schema-v16-verifier" \
  "$worker_root/cats-usage-terminal-receipt-verifier" "$worker_root/cats-noded"
chmod 0644 "$worker_root/guest-runtime-release.v1/manifest.v1.json"
bundle="$root/cats-worker.tar.zst"
tar -cf - -C "$worker_root" . | zstd -q -o "$bundle"
bundle_sha256=$(sha256sum -- "$bundle" | awk '{print $1}')

# --- real public trust generated by the repository authority tool.
trust_dir="$root/trust"
mkdir -m 0700 "$trust_dir"
trust_file="$trust_dir/production-cutover-operator-trust.v1.json"
python3 -B "$trust_tool" generate \
  --deployment-id fixture-operator-tools \
  --release-id "sha256:$(printf '7%.0s' {1..64})" \
  --source-commit "$(printf '3%.0s' {1..40})" \
  --credential-id fixture-operator-tools \
  --aws-partition aws \
  --account-id 123456789012 \
  --role-arn arn:aws:iam::123456789012:role/cats-production-cutover \
  --private-key-out "$trust_dir/operator-private-key.pem" \
  --trust-out "$trust_file" \
  --generation-receipt-out \
  "$trust_dir/production-cutover-operator-trust-generation.receipt.json" \
  --openssl "$openssl_binary" > /dev/null

sysroot="$root/sysroot"
mkdir -m 0755 "$sysroot"
base_command=(
  "$installer"
  --bundle "$bundle"
  --bundle-sha256 "$bundle_sha256"
  --trust-file "$trust_file"
  --install-root "$sysroot"
)

# 1. Dry run validates everything and mutates nothing.
"${base_command[@]}" --dry-run > "$root/dry-run.log"
grep -q "would install $sysroot/opt/cats/bin/cats$" "$root/dry-run.log" \
  || fail "dry run did not plan the cats CLI"
[[ -z $(find "$sysroot" -mindepth 1) ]] || fail "dry run mutated the install root"

# 2. First real install places exactly the operator toolchain and trust.
"${base_command[@]}" > "$root/install.log"
for name in cats cats-usage-schema-v16-verifier \
  cats-usage-terminal-receipt-verifier; do
  installed="$sysroot/opt/cats/bin/$name"
  [[ -f $installed && ! -L $installed ]] || fail "missing installed tool: $name"
  cmp -s -- "$worker_root/$name" "$installed" || fail "content drifted: $name"
  mode=$(python3 -B -c \
    'import os,stat,sys;print(oct(stat.S_IMODE(os.lstat(sys.argv[1]).st_mode)))' \
    "$installed")
  [[ $mode == 0o755 ]] || fail "tool mode is not 0755: $name ($mode)"
  links=$(python3 -B -c \
    'import os,sys;print(os.lstat(sys.argv[1]).st_nlink)' "$installed")
  [[ $links == 1 ]] || fail "tool has extra hard links: $name"
done
installed_trust="$sysroot/etc/cats/production-cutover-operator-trust.v1.json"
cmp -s -- "$trust_file" "$installed_trust" || fail "trust content drifted"
trust_mode=$(python3 -B -c \
  'import os,stat,sys;print(oct(stat.S_IMODE(os.lstat(sys.argv[1]).st_mode)))' \
  "$installed_trust")
[[ $trust_mode == 0o644 ]] || fail "trust mode is not 0644 ($trust_mode)"
[[ ! -e $sysroot/opt/cats/bin/cats-noded ]] || fail "worker daemon leaked in"
[[ ! -e $sysroot/opt/cats/guest ]] || fail "guest payload leaked in"
[[ -z $(find "$sysroot" -name '*.service' -o -name 'cloud-hypervisor') ]] \
  || fail "worker service artifacts leaked in"

# 3. Replay is exact: same inodes, nothing rewritten.
inodes_before=$(find "$sysroot" -type f -exec ls -i {} + | sort)
"${base_command[@]}" > "$root/replay.log"
grep -q "already exact" "$root/replay.log" || fail "replay did not report exact"
inodes_after=$(find "$sysroot" -type f -exec ls -i {} + | sort)
[[ "$inodes_before" == "$inodes_after" ]] || fail "replay rewrote installed files"

# 4. A drifted installed file fails closed without --replace, in real and
#    dry-run mode, and stays byte-identical; --replace restores it.
tampered="$sysroot/opt/cats/bin/cats-usage-schema-v16-verifier"
printf '#!/bin/sh\necho tampered\n' > "$tampered"
tampered_before=$(sha256sum -- "$tampered")
expect_failure "install over drifted file" "${base_command[@]}"
expect_failure "dry-run over drifted file" "${base_command[@]}" --dry-run
[[ "$tampered_before" == $(sha256sum -- "$tampered") ]] \
  || fail "fail-closed run modified the drifted file"
"${base_command[@]}" --replace > "$root/replace.log"
cmp -s -- "$worker_root/cats-usage-schema-v16-verifier" "$tampered" \
  || fail "--replace did not restore exact release content"

# 5. Digest mismatch is rejected before any extraction.
expect_failure "wrong bundle digest" "$installer" \
  --bundle "$bundle" \
  --bundle-sha256 "$(printf '0%.0s' {1..64})" \
  --trust-file "$trust_file" \
  --install-root "$sysroot" --dry-run

# 6. Unsafe archives are rejected: parent traversal, duplicates, symlinks and
#    a missing operator tool member.
evil_dir="$root/evil"
mkdir -m 0700 "$evil_dir"
python3 -B - "$worker_root" "$evil_dir" <<'PY'
import io
import subprocess
import sys
import tarfile
from pathlib import Path

worker_root = Path(sys.argv[1])
evil_dir = Path(sys.argv[2])


def base_members(archive: tarfile.TarFile) -> None:
    for name in (
        "cats",
        "cats-usage-schema-v16-verifier",
        "cats-usage-terminal-receipt-verifier",
    ):
        archive.add(worker_root / name, arcname=f"./{name}")


def write(name: str, build) -> None:
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w") as archive:
        build(archive)
    compressed = subprocess.run(
        ["zstd", "-q", "-o", str(evil_dir / name)],
        input=raw.getvalue(),
        check=True,
    )
    assert compressed.returncode == 0


def traversal(archive: tarfile.TarFile) -> None:
    base_members(archive)
    payload = b"evil\n"
    member = tarfile.TarInfo("../evil")
    member.size = len(payload)
    archive.addfile(member, io.BytesIO(payload))


def duplicate(archive: tarfile.TarFile) -> None:
    base_members(archive)
    archive.add(worker_root / "cats", arcname="./cats")


def symlink(archive: tarfile.TarFile) -> None:
    base_members(archive)
    member = tarfile.TarInfo("./evil-link")
    member.type = tarfile.SYMTYPE
    member.linkname = "/etc/passwd"
    archive.addfile(member)


def missing(archive: tarfile.TarFile) -> None:
    archive.add(worker_root / "cats", arcname="./cats")


write("traversal.tar.zst", traversal)
write("duplicate.tar.zst", duplicate)
write("symlink.tar.zst", symlink)
write("missing.tar.zst", missing)
PY
for evil in traversal duplicate symlink missing; do
  evil_bundle="$evil_dir/cats-worker.tar.zst"
  cp -f -- "$evil_dir/$evil.tar.zst" "$evil_bundle"
  evil_sha256=$(sha256sum -- "$evil_bundle" | awk '{print $1}')
  expect_failure "unsafe archive: $evil" "$installer" \
    --bundle "$evil_bundle" \
    --bundle-sha256 "$evil_sha256" \
    --trust-file "$trust_file" \
    --install-root "$sysroot" --dry-run
done

# 7. Invalid trust inputs are rejected before any bundle work.
bad_version="$root/bad-version-trust.json"
python3 -B - "$trust_file" "$bad_version" <<'PY'
import json
import sys
from pathlib import Path

trust = json.loads(Path(sys.argv[1]).read_bytes())
trust["version"] = 2
Path(sys.argv[2]).write_bytes(
    json.dumps(
        trust, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("ascii")
)
PY
chmod 0644 "$bad_version"
expect_failure "wrong trust version" "$installer" \
  --bundle "$bundle" --bundle-sha256 "$bundle_sha256" \
  --trust-file "$bad_version" --install-root "$sysroot" --dry-run

noncanonical="$root/noncanonical-trust.json"
cat "$trust_file" > "$noncanonical"
printf '\n' >> "$noncanonical"
chmod 0644 "$noncanonical"
expect_failure "noncanonical trust" "$installer" \
  --bundle "$bundle" --bundle-sha256 "$bundle_sha256" \
  --trust-file "$noncanonical" --install-root "$sysroot" --dry-run

echo "install-operator-tools fixture passed"
